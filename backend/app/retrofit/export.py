"""Write the offline snapshot the frontend uses when no backend is running.

It runs the canonical demo flow on a throwaway in-memory store, so the snapshot is exactly what the live backend
would return (timestamps and timings zeroed so the file is stable). `tests/retrofit/test_snapshot.py` fails if the
committed snapshot drifts from the code. Regenerate: `python -m app.retrofit.export`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .decisions import Store
from .workflow import Retrofit

TARGET = Path(__file__).resolve().parents[3] / "frontend" / "src" / "retrofit" / "snapshot.json"
VOLATILE = {"at", "created", "accepted_at", "requested", "decided_at", "approved_at", "elapsed_s"}


def _stable(x: Any) -> Any:
    if isinstance(x, dict):
        return {k: 0 if k in VOLATILE else _stable(v) for k, v in x.items()}
    if isinstance(x, list):
        return [_stable(v) for v in x]
    return x


def build() -> dict[str, Any]:
    from .monitor import snapshot as monitor_snapshot

    flow = Retrofit(Store(":memory:"))
    out: dict[str, Any] = {"note": "Generated by python -m app.retrofit.export. SYNTHETIC demo data."}
    out["original"] = flow.original("h1")
    out["drawing"] = flow.site("h1").drawing_text
    out["flag"] = flow.flag("h1")
    decision = flow.decide("h1", out["flag"]["flags"][0]["zone"], "confirmed", "J. Chen")
    out["decision"] = decision
    out["proposal"] = flow.propose("h1")
    out["candidate_report"] = flow.test("h1", "candidate")
    out["regression"] = flow.save_regression("h1", decision["id"], "J. Chen")
    out["candidate_with_regression"] = flow.test("h1", "candidate")
    out["h2_original"] = flow.original("h2")
    out["h2_flag"] = flow.flag("h2")
    out["h2_decision"] = flow.decide("h2", out["h2_flag"]["flags"][0]["zone"], "confirmed", "K. Osei")
    out["h2_proposal"] = flow.propose("h2")
    out["h2_candidate_report"] = flow.test("h2", "candidate")
    out["package_v1"] = flow.accept("h1", "Maya R.")
    out["readiness_v1"] = flow.readiness("h1")
    out["firmware"] = flow.revalidate("h1", "2.4.0")
    out["firmware_approved"] = flow.approve("h1", out["firmware"]["approval"]["id"], "approved", "Maya R.")
    out["readiness"] = flow.readiness("h1")
    out["handover"] = flow.handover("h1")
    out["handover_md"] = flow.handover_md("h1")
    out["monitor"] = monitor_snapshot(flow)
    return _stable(out)


def write() -> None:
    TARGET.write_text(json.dumps(build(), sort_keys=True, separators=(",", ":")) + "\n")


if __name__ == "__main__":
    write()
